// Identity and media projections derived from their masters in design/. Everything written here is generated and
// ignored by Git; the masters are the approved brand exports (icon, favicon) and Yoru's spritesheet.
//
//   public/favicon.svg            the return's adaptive favicon, unchanged (static, never the animated mark)
//   public/favicon-192.png        square raster favicon on the glow tile
//   public/apple-touch-icon.png   180x180 glow tile, full-bleed (iOS rounds the corners)
//   public/yoru/sheet-1x.webp     Yoru's spritesheet at display size
//   public/yoru/sheet-2x.webp     ... and for high-density screens
//   src/generated/yoru-doze.ts    one sleeping frame as a data URI, for the self-contained 503
//   public/yoru/resident/<family>-1x.webp, -2x.webp   the resident's animation families
//   src/generated/yoru-families.ts                    their manifests
import { cpSync, rmSync, copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const marks = join(root, 'brand', 'bundle', 'works');
const yoruMaster = join(root, 'design', 'the-walk', 'assets', 'yoru-spritesheet.webp');
const pub = join(root, 'public');

rmSync(join(pub, 'brand', 'works'), { recursive: true, force: true });
cpSync(marks, join(pub, 'brand', 'works'), { recursive: true });

mkdirSync(join(pub, 'yoru'), { recursive: true });
mkdirSync(join(root, 'src', 'generated'), { recursive: true });

// ---------- favicon and app icons ----------
copyFileSync(join(marks, 'assets', 'icon-favicon', 'on-light-adaptive.svg'), join(pub, 'favicon.svg'));

// The selected app-icon tile (finishing sheet, tile 2): the Works icon on a dark tile with the Walk's orange and
// magenta glowing in from the corners. The icon geometry is the return's 32-grid icon at 62% of the tile.
copyFileSync(join(marks, 'assets/icon-touch/universal-180x180.png'), join(pub, 'apple-touch-icon.png'));
copyFileSync(join(marks, 'assets/icon-application/universal-192x192.png'), join(pub, 'favicon-192.png'));

// ---------- Yoru ----------
// The master is a 2x sheet: frames of 192x208 on a 1536x1872 canvas; the site shows them at 96x104.
await sharp(yoruMaster).webp({ quality: 82, alphaQuality: 90, effort: 6 }).toFile(join(pub, 'yoru', 'sheet-2x.webp'));
await sharp(yoruMaster).resize(768, 936).webp({ quality: 85, alphaQuality: 90, effort: 6 }).toFile(join(pub, 'yoru', 'sheet-1x.webp'));

// The 503 is served when the site may not be, so it carries Yoru inline: the first sleeping frame (row 6, column 4).
const doze = await sharp(yoruMaster)
  .extract({ left: 3 * 192, top: 5 * 208, width: 192, height: 208 })
  .resize(96, 104)
  .webp({ quality: 80, alphaQuality: 85 })
  .toBuffer();
writeFileSync(
  join(root, 'src', 'generated', 'yoru-doze.ts'),
  `// Generated by scripts/generate-identity-assets.mjs. Do not edit.\nexport const YORU_DOZE = 'data:image/webp;base64,${doze.toString('base64')}';\n`,
);

// ---------- Yoru, the resident ----------
// The resident's animation families, packed by the sprite studio (design/yoru/sheets/, lossless at twice display
// size), as lossy 1x/2x sheets the browser loads per family, and their manifests as one module the engine imports.
// A sheet is only re-encoded when its master changed: these are large and the dev server runs this on every start.
const RESIDENT_FAMILIES = ['presence', 'everyday', 'sleep', 'curious', 'reactions', 'guest', 'nook', 'ladder', 'ladder-prop'];
const sheets = join(root, 'design', 'yoru', 'sheets');
const residentOut = join(pub, 'yoru', 'resident');
mkdirSync(residentOut, { recursive: true });
const manifests = {};
for (const family of RESIDENT_FAMILIES) {
  const master = join(sheets, `${family}.webp`);
  manifests[family] = JSON.parse(readFileSync(join(sheets, `${family}.json`), 'utf8'));
  const x2 = join(residentOut, `${family}-2x.webp`);
  const x1 = join(residentOut, `${family}-1x.webp`);
  if (existsSync(x1) && existsSync(x2) && statSync(x1).mtimeMs > statSync(master).mtimeMs) continue;
  const { width } = await sharp(master).metadata();
  await sharp(master).webp({ quality: 80, alphaQuality: 85, effort: 6 }).toFile(x2);
  await sharp(master).resize(Math.round(width / 2)).webp({ quality: 82, alphaQuality: 88, effort: 6 }).toFile(x1);
}
writeFileSync(
  join(root, 'src', 'generated', 'yoru-families.ts'),
  `// Generated by scripts/generate-identity-assets.mjs from design/yoru/sheets. Do not edit.\nimport type { SheetManifest } from '../features/yoru/clips';\n\nexport const YORU_FAMILIES: Record<string, SheetManifest> = ${JSON.stringify(manifests)};\n`,
);

console.log(`Identity assets: favicon, glow-tile icons, Yoru sheets (1x/2x), inline doze frame (${doze.length} bytes), ${RESIDENT_FAMILIES.length} resident families.`);
