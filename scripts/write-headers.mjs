// Writes artifacts/site/_headers for the static pages after `astro build`: security headers and one site-wide
// Content-Security-Policy that pins every inline script the static pages ship by hash, `noindex, nosnippet` on the
// legal pages, and long caching for fingerprinted and versioned assets. The Worker sets its own CSP on the two pages it
// serves (home and contact). One CSP rule only: Cloudflare joins duplicate headers, which would intersect policies.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { contentSecurityPolicy, scriptHashes } from '../shared/csp.ts';

const out = fileURLToPath(new URL('../artifacts/site/', import.meta.url));

function htmlFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return htmlFiles(path);
    return name.endsWith('.html') ? [path] : [];
  });
}

const hashes = new Set();
for (const file of htmlFiles(out)) {
  const path = relative(out, file).replaceAll('\\', '/');
  // The 503 is a custom error page served by the provider; it has no scripts.
  if (path === '503.html') continue;
  for (const hash of await scriptHashes(readFileSync(file, 'utf8'))) hashes.add(hash);
}

const security = [
  'X-Content-Type-Options: nosniff',
  'Referrer-Policy: strict-origin-when-cross-origin',
  'Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()',
  'Cross-Origin-Opener-Policy: same-origin',
  'Strict-Transport-Security: max-age=31536000',
  `Content-Security-Policy: ${contentSecurityPolicy([...hashes].sort())}`,
];
const rule = (path, lines) => `${path}\n${lines.map((line) => `  ${line}`).join('\n')}\n`;
const legal = ['X-Robots-Tag: noindex, nosnippet'];
const immutable = ['Cache-Control: public, max-age=31536000, immutable'];
const week = ['Cache-Control: public, max-age=604800'];

const headers = [
  '# Generated by scripts/write-headers.mjs during the build. Do not edit.',
  rule('/*', security),
  rule('/impressum', legal),
  rule('/impressum/*', legal),
  rule('/privacy', legal),
  rule('/privacy/*', legal),
  rule('/503.html', ['X-Robots-Tag: noindex']),
  rule('/_astro/*', immutable),
  rule('/fonts/*', immutable),
  rule('/yoru/*', week),
  rule('/social/*', week),
].join('\n');

writeFileSync(join(out, '_headers'), headers);
console.log(`_headers: site CSP pins ${hashes.size} inline script hash(es); legal pages noindex, nosnippet.`);
