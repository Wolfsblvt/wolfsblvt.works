// Self-hosted fonts, Latin and Latin Extended only. Copies the selected Fontsource WOFF2 files into public/fonts/ and
// writes src/styles/fonts.generated.css with @font-face rules under the family names the site's CSS uses. Both
// outputs are generated and ignored by Git; the pinned Fontsource packages are the source.
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'public', 'fonts');
const cssOut = join(root, 'src', 'styles', 'fonts.generated.css');
const SUBSETS = ['latin', 'latin-ext'];

// family: the name the site's CSS uses; css: the Fontsource stylesheet whose rules are filtered by subset.
const FONTS = [
  { family: 'Literata', pkg: '@fontsource-variable/literata', css: ['opsz.css', 'opsz-italic.css'], format: 'woff2-variations' },
  { family: 'Albert Sans', pkg: '@fontsource-variable/albert-sans', css: ['wght.css'], format: 'woff2-variations' },
  { family: 'Shantell Sans', pkg: '@fontsource/shantell-sans', css: ['400.css', '500.css', '400-italic.css'], format: 'woff2' },
  { family: 'IBM Plex Sans', pkg: '@fontsource/ibm-plex-sans', css: ['400.css', '600.css'], format: 'woff2' },
  { family: 'IBM Plex Mono', pkg: '@fontsource/ibm-plex-mono', css: ['400.css', '500.css'], format: 'woff2' },
  { family: 'Special Elite', pkg: '@fontsource/special-elite', css: ['400.css'], format: 'woff2' },
];

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const rules = [];
let files = 0;
for (const font of FONTS) {
  const pkgDir = join(root, 'node_modules', ...font.pkg.split('/'));
  for (const sheet of font.css) {
    const css = readFileSync(join(pkgDir, sheet), 'utf8');
    for (const match of css.matchAll(/\/\* ([^*]+) \*\/\s*@font-face\s*\{([^}]+)\}/g)) {
      const [, label, body] = match;
      const subset = SUBSETS.find((s) => label.includes(`-${s}-`) && !(s === 'latin' && label.includes('-latin-ext-')));
      if (!subset) continue;
      const url = /url\(\.\/files\/([^)]+)\)/.exec(body)?.[1];
      if (!url) throw new Error(`No font file in ${font.pkg}/${sheet} rule ${label}`);
      copyFileSync(join(pkgDir, 'files', url), join(outDir, url));
      files++;
      const keep = body
        .split(';')
        .map((d) => d.trim())
        .filter((d) => /^(font-style|font-weight|font-stretch|unicode-range)/.test(d));
      rules.push(
        `@font-face {\n  font-family: '${font.family}';\n  font-display: swap;\n  ${keep.join(';\n  ')};\n  src: url('/fonts/${url}') format('${font.format}');\n}`,
      );
    }
  }
}

writeFileSync(
  cssOut,
  `/* Generated by scripts/prepare-fonts.mjs from the pinned Fontsource packages. Do not edit. */\n${rules.join('\n')}\n`,
);
console.log(`Fonts: ${files} files, ${rules.length} @font-face rules (Latin and Latin Extended).`);
